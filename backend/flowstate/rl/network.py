"""The small connected network RL is trained and evaluated on: a 2 x 2 grid of signalised junctions.

Four junctions (A0, B0, A1, B1), two-lane streets, eight entry/exit stubs. Generated by SUMO's own
``netgenerate`` so it is reproducible from the code alone; the layout it yields (two green stages per
junction, opposite approaches together, permissive turns) is read back from the generated program.
"""

from __future__ import annotations

import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from .. import sumo_env
from . import config as C

NET_NAME = "rl_grid"


def build_net(directory: Path) -> Path:
    """Generate (or reuse) the network file in ``directory``."""
    directory.mkdir(parents=True, exist_ok=True)
    out = directory / f"{NET_NAME}.net.xml"
    if out.exists():
        return out
    cmd = [sumo_env.binary("netgenerate"), "--grid", "--grid.x-number", "2", "--grid.y-number", "2",
           "--grid.x-length", str(C.BLOCK_LENGTH_M), "--grid.y-length", str(C.BLOCK_LENGTH_M),
           "--grid.attach-length", str(C.ATTACH_LENGTH_M), "--default.lanenumber", str(C.LANES),
           "--default.speed", str(C.SPEED_MS), "-j", "traffic_light", "--no-turnarounds", "--output-file", str(out)]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode or not out.exists():
        raise RuntimeError(f"netgenerate failed: {r.stderr[-400:]}")
    return out


@dataclass
class Junction:
    id: str
    n_links: int
    greens: list[str]  # green-stage states, in cycle order
    yellows: list[str]  # clearance state that follows each green
    approach_edges: dict[str, str] = field(default_factory=dict)  # direction -> incoming edge
    out_edges: dict[str, str] = field(default_factory=dict)  # direction an approach heads to -> outgoing edge
    served: list[list[str]] = field(default_factory=list)  # approaches that have a green in each stage
    neighbours: list[str] = field(default_factory=list)


@dataclass
class GridInfo:
    junctions: dict[str, Junction]
    entry_edges: list[str]
    exit_edges: list[str]
    internal_edges: list[str]
    edge_length: dict[str, float]
    edge_lanes: dict[str, int]

    def capacity(self, edge: str) -> float:
        """Vehicles an edge holds when queued."""
        return max(1.0, self.edge_length[edge] * self.edge_lanes[edge] / C.SLOT_M)


def _heading(x0: float, y0: float, x1: float, y1: float) -> str:
    dx, dy = x1 - x0, y1 - y0
    if abs(dy) >= abs(dx):
        return "N" if dy > 0 else "S"
    return "E" if dx > 0 else "W"


def read_grid(net_path: Path) -> GridInfo:
    import sumolib

    net = sumolib.net.readNet(str(net_path), withInternal=False, withPrograms=True)
    junctions: dict[str, Junction] = {}
    root_tls = {t.getID(): t for t in net.getTrafficLights()}
    for jid in C.CONTROLLED:
        node = net.getNode(jid)
        prog = next(iter(root_tls[jid].getPrograms().values()))
        phases = prog.getPhases()
        greens, yellows = [], []
        for i, ph in enumerate(phases):
            if "y" in ph.state.lower() and "G" not in ph.state:
                continue
            if "G" in ph.state or "g" in ph.state:
                greens.append(ph.state)
                nxt = phases[(i + 1) % len(phases)].state
                yellows.append(nxt if "y" in nxt else "".join("y" if c in "Gg" else "r" for c in ph.state))
        j = Junction(jid, len(greens[0]), greens, yellows)
        for e in node.getIncoming():
            if e.getFromNode().getID() == jid:
                continue
            fx, fy = e.getFromNode().getCoord()
            tx, ty = node.getCoord()
            # an approach is named by the side of the junction it comes from
            j.approach_edges[{"N": "S", "S": "N", "E": "W", "W": "E"}[_heading(fx, fy, tx, ty)]] = e.getID()
        for e in node.getOutgoing():
            fx, fy = node.getCoord()
            tx, ty = e.getToNode().getCoord()
            j.out_edges[_heading(fx, fy, tx, ty)] = e.getID()
        j.neighbours = sorted(e.getFromNode().getID() for e in node.getIncoming() if e.getFromNode().getID() in C.CONTROLLED)
        # which approaches does each green stage serve? link order = controlled-link order of the tls
        links = root_tls[jid].getLinks()
        edge_of_link = [lst[0][0].getEdge().getID() for _, lst in sorted(links.items())]
        by_edge = {eid: d for d, eid in j.approach_edges.items()}
        for g in greens:
            j.served.append(sorted({by_edge[edge_of_link[i]] for i, c in enumerate(g) if c in "Gg" and edge_of_link[i] in by_edge}))
        junctions[jid] = j
    entry, exits, internal = [], [], []
    length, lanes = {}, {}
    for e in net.getEdges():
        eid = e.getID()
        length[eid], lanes[eid] = e.getLength(), e.getLaneNumber()
        a, b = e.getFromNode().getID(), e.getToNode().getID()
        if a not in C.CONTROLLED and b in C.CONTROLLED:
            entry.append(eid)
        elif b not in C.CONTROLLED and a in C.CONTROLLED:
            exits.append(eid)
        elif a in C.CONTROLLED and b in C.CONTROLLED:
            internal.append(eid)
    return GridInfo(junctions, sorted(entry), sorted(exits), sorted(internal), length, lanes)
